"""Collects every channel from every run into results/channels.md and results/channels.csv.

    uv run python scripts/aggregate_channels.py

A channel is one way for Bob's strength to reach the judge. Each row compares a condition with the judge alone
(J1) on the same items. Notes and checks use intention-to-treat: an item without them keeps its J1 verdict.
Reads only results/*/summary.json.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"

# (condition, label, kind). Order sets the row order in each run.
CHANNELS = [
    ("j1", "Judge alone (J1)", "baseline"),
    ("bob_alone", "Bob alone, v1", "critic"),
    ("bob_solve_x4", "Bob alone, solve x4", "critic"),
    ("j1_bob_itt", "Notes, v1", "verdict-free"),
    ("j1_bob_x4_itt", "Notes, solve-x4 working", "verdict-free"),
    ("checks_bob_judge_itt", "Checks by Bob", "verdict-free"),
    ("checks_self_judge_itt", "Checks by the judge (no Bob)", "control"),
    ("j1_testimony", "Testimony, v1 verdict", "verdict"),
    ("j1_testimony_x4", "Testimony, solve-x4 verdict", "verdict"),
]
FIELDS = ["run", "judge", "bob", "channel", "kind", "n", "accuracy", "accuracy_lo", "accuracy_hi",
          "d_accuracy", "d_accuracy_lo", "d_accuracy_hi", "mcnemar_p", "auroc", "auroc_lo", "auroc_hi",
          "d_auroc", "d_auroc_lo", "d_auroc_hi"]


def rows_for(run_dir: Path) -> list[dict]:
    s = json.loads((run_dir / "summary.json").read_text(encoding="utf-8"))
    models = s["config"]["models"]
    out = []
    for cond, label, kind in CHANNELS:
        pc = s["per_condition"].get(cond)
        if not pc:
            continue
        row = {"run": run_dir.name, "judge": models["judge"]["model"], "bob": models["bob"]["model"],
               "channel": label, "kind": kind, "n": pc["n"], "accuracy": pc["accuracy"],
               "accuracy_lo": pc["accuracy_ci95"][0], "accuracy_hi": pc["accuracy_ci95"][1],
               "auroc": pc["auroc"], "auroc_lo": pc["auroc_ci95"][0], "auroc_hi": pc["auroc_ci95"][1]}
        vs = s["vs_j1"].get(cond)
        if vs:
            c, a = vs["comparison"], vs["auroc_comparison"]
            row.update(n=c["n"], d_accuracy=c["delta_accuracy"], d_accuracy_lo=c["ci95"][0],
                       d_accuracy_hi=c["ci95"][1], mcnemar_p=c["mcnemar_p"], d_auroc=a["delta_auroc"],
                       d_auroc_lo=a["ci95"][0], d_auroc_hi=a["ci95"][1])
        out.append(row)
    return out


def pct(x) -> str:
    return f"{100 * x:.1f}"


def fmt(r: dict) -> list[str]:
    acc = f"{pct(r['accuracy'])} [{pct(r['accuracy_lo'])}, {pct(r['accuracy_hi'])}]"
    auc = f"{r['auroc']:.3f} [{r['auroc_lo']:.3f}, {r['auroc_hi']:.3f}]"
    if "d_accuracy" not in r:
        return [acc, "–", "–", auc, "–"]
    d = f"{100 * r['d_accuracy']:+.1f} [{100 * r['d_accuracy_lo']:+.1f}, {100 * r['d_accuracy_hi']:+.1f}]"
    da = f"{r['d_auroc']:+.3f} [{r['d_auroc_lo']:+.3f}, {r['d_auroc_hi']:+.3f}]"
    bold = r["d_accuracy_lo"] > 0 and r["kind"] != "critic"
    return [acc, f"**{d}**" if bold else d, f"{r['mcnemar_p']:.3g}", auc, da]


def main() -> None:
    rows = [r for d in sorted(RESULTS.glob("0*")) if (d / "summary.json").exists() for r in rows_for(d)]
    with open(RESULTS / "channels.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)

    lines = ["# Channels: all runs", "",
             "Generated by `scripts/aggregate_channels.py`. Do not edit by hand.",
             "Every Δ is against the judge alone (J1) on the same items, with a 95% CI that resamples whole questions.",
             "n is the number of items shared with J1. Accuracy and AUROC use all items of the condition.",
             "p is the exact McNemar test. Bold: the CI of Δ accuracy is above zero for a judge channel.", ""]
    for run in dict.fromkeys(r["run"] for r in rows):
        rs = [r for r in rows if r["run"] == run]
        lines += [f"## {run}", "", f"Judge `{rs[0]['judge']}`, Bob `{rs[0]['bob']}`.", "",
                  "| Channel | Kind | n | Accuracy % | Δ accuracy (pts) | p | AUROC | Δ AUROC |",
                  "|---|---|---|---|---|---|---|---|"]
        lines += [f"| {r['channel']} | {r['kind']} | {r['n']} | " + " | ".join(fmt(r)) + " |" for r in rs]
        lines.append("")
    (RESULTS / "channels.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} rows to results/channels.md and results/channels.csv")


if __name__ == "__main__":
    main()
